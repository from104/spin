// §6.2 / §7.1 팀 표식 — **세 경로(화면 · PNG · 인쇄)가 공유하는 단 하나의 출처.**
//
// ── 4.6 이 닫은 결함 ────────────────────────────────────────────────────────────────
// 2026-08-12 이전까지 두 팀을 가르는 채널은 **차체 채움색 하나뿐**이었다(#d93a3a / #1f6bb8).
// 이건 확률이 아니라 **확정적 결함**이다:
//   · 흑백 레이저로 뽑으면 두 색의 상대휘도가 L .181 / .143 — 회색조로 0.038 밖에 안 벌어진다
//     (검산은 core/colors.ts 의 relLuminance). 하프톤을 거치면 사실상 같은 회색이고,
//     코치는 종이를 보며 누가 우리 편인지 **알 수 없다**.
//   · 적록 색각 이상(남성 약 8%)에게는 화면에서도 이미 빨강/파랑 구분이 무너진다.
//
// ── 무엇을 더했고 왜 그것인가 ───────────────────────────────────────────────────────
// 두 채널을 더했다. 하나는 **색을 통째로 지워도 남는 기하 채널**, 하나는 **회색조에서
// 살아남는 명도 채널**이다. 둘 다 차체의 **이미 있는 도형**에만 얹으므로 새 여백이 필요 없다.
//
//  ① 테두리 파선 패턴(`strokeDash`) — 우리팀 실선 / 상대팀 파선. **주 채널.**
//     · 색 속성(fill/stroke)을 전부 제거해도 `stroke-dasharray` 는 남는다 → 팀 구분 정보가
//       색 채널 **밖에** 존재함을 기계적으로 증명할 수 있다(teamMonochrome.test.tsx).
//     · 자리 비용 0 — 차체 둘레(32.5×20 둥근 사각, 둘레 ≈ 100 px)를 쓴다. 등번호는
//       centroidOffsetPx(+9.75)의 한가운데라 **2/3 로 줄인 글자(20×2/3)를 하나도 가리지 않는다.**
//     · 크기 검산: 주기 8 px 이라 둘레에 약 15 토막이 생긴다. A4 가로 인쇄에서 코트 높이
//       110 mm(4.5 print.css) → 풀코트 vbH 525 px 기준 0.21 mm/px 이므로 파선 한 토막이
//       1.05 mm · 틈 0.63 mm — 종이에서 '점선'으로 읽히는 하한(약 0.5 mm) 위다.
//       화면에서는 배율 1.0 만 되어도 5 CSS px 토막이라 작은 칩에서도 보인다.
//
//  ② 볼가드 톤(`guardFill`) — 우리팀 **밝은** 앞범퍼 / 상대팀 **어두운** 앞범퍼. **보조 채널.**
//     · 파선은 선이라 극단적 축소(썸네일·멀리 본 전체 코트)에서 뭉개져 실선처럼 보인다.
//       그때는 '면'이 남아야 한다 — 가드는 4.875×20 px 의 면이고 인쇄에서 1.0×4.2 mm 다.
//     · 흰 .24 를 얹은 면과 검정 .34 를 얹은 면은 **회색조로 옮겨도** 서로 반대쪽으로 벌어진다
//       (예: 우리팀 #d93a3a→회색 118 위에 흰 .24 = 151, 상대 #1f6bb8→105 위에 검정 .34 = 68).
//     · ⚠️ 이 채널은 **색 속성 제거 테스트로는 증명되지 않는다**(fill 값이 곧 정보라서).
//       그래서 주 채널을 파선으로 두었다. 가드 톤만 남기고 파선을 빼면 완료 판정이 무너진다.
//
// ── 고르지 않은 것들과 그 이유 ──────────────────────────────────────────────────────
//  · **번호 접두**(예: 상대팀만 `'4`): 등번호는 이미 20×2/3 으로 줄여 놓은 상태다(기현 지시
//    2026-08-11). 글자를 하나 더 붙이면 칩 폭 25 px 안에서 두 글자가 되어 그 축소의 이유였던
//    '답답함'이 그대로 돌아온다. 판단 기준 ③('등번호 표시를 방해하지 않는가')에 정면으로 걸린다.
//  · **차체 모양 변경**(원 vs 사각 등): 차체 사각형은 물리 바디의 발자국이기도 하다
//    (CHAIR.lengthPx/widthPx). 그림에서만 모양을 바꾸면 "밀면 어디까지 닿는가"가 거짓이 된다.
//  · **차체 안쪽 줄무늬**: 줄이 등번호 뒤를 지나 흰 글자의 대비를 갉는다(기준 ③ 위반).
//
// ── 적용하지 않은 한 곳: 썸네일 ─────────────────────────────────────────────────────
// `CourtThumbnail.tsx` 는 휠체어를 **r=6 원**으로 그린다(목록 카드·스텝 칩). 둘레가 38 px 라
// 주기 8 px 파선이 5토막밖에 안 되고, 카드에서 실제 크기가 수십 CSS px 로 축소되면 점선이
// 그냥 흐린 실선으로 뭉갠다 — 즉 여기서는 이 표식이 **작동하지 않는다.** 억지로 넣으면
// "표식이 있으니 됐다" 는 거짓 안전감만 생긴다. 썸네일은 판을 읽는 화면이 아니라 드릴을
// 고르는 화면이라 팀 판별이 과업이 아니다. 필요해지면 그때는 파선이 아니라 **원/사각 실루엣**
// 같은 다른 채널을 골라야 한다.
//
// ── 왜 여기(src/render)에 있는가 ────────────────────────────────────────────────────
// 4.4 는 `features/present/PresentObjects.tsx` 의 `chairColorFor` 를 **일부러 복제**했다
// (React 컴포넌트 모듈을 내보내기 경로가 붙들면 안 되기 때문). 4.6 은 그 판단을 유지하되
// 복제를 **없앤다** — 이 파일은 React 도 DOM 도 없는 순수 모듈이고, render 층은 화면·인쇄·
// 내보내기 셋 다가 이미 의존하는 아래층이다. 표식이 한 곳에서만 나오지 않으면 "화면에선
// 구분되는데 종이에선 안 되는" 상태가 조용히 생긴다 — 그게 이 항목이 막으려는 사고다.
import { inkFor, strokeFor } from '../core/colors.ts';
import type { ChairDef, TeamSide, TeamStyle } from '../model/drill.ts';

/** 색이 아닌 채널로 팀을 가르는 값. 팀 소속(`TeamSide`)에서만 나온다 —
 *  ⚠️ 개별 색 지정(`ChairDef.color`, §3.5)이 팀 색을 덮어써도 이 표식은 **덮이지 않는다.**
 *  개별 색이야말로 색 채널이 통째로 무너지는 경우라, 그때 남는 것이 이 표식뿐이다. */
export interface TeamPattern {
  /** 차체 테두리 파선 패턴. `undefined` = 실선. */
  strokeDash?: string;
  /** 볼가드(앞범퍼) 채움. 차체 색 위에 얹는 알파라 팀 색이 무엇이든 밝기 방향이 유지된다. */
  guardFill: string;
}

/** 파선 주기 = 5 + 3 = 8 px. 위 머리말의 크기 검산이 이 두 숫자에 걸려 있다. */
const AWAY_DASH = '5 3';

export const TEAM_PATTERNS: Readonly<Record<TeamSide, TeamPattern>> = Object.freeze({
  // 우리팀 = 실선 + 밝은 가드. '기본형'을 우리팀에 둔 이유: 코치가 보는 판에서 수가 많고
  // 눈이 오래 머무는 쪽이 우리팀이다. 장식이 적은 쪽을 거기에 둔다.
  home: Object.freeze({ guardFill: 'rgba(255,255,255,.24)' }),
  away: Object.freeze({ strokeDash: AWAY_DASH, guardFill: 'rgba(0,0,0,.34)' }),
});

export function teamPatternFor(team: TeamSide): TeamPattern {
  return TEAM_PATTERNS[team];
}

/** 칩 하나를 그리는 데 필요한 팀 표식 전량. 여기 없는 값으로 팀을 구분하면 안 된다. */
export interface TeamMark {
  /** 차체 채움색. */
  fill: string;
  /** 차체 테두리색. **차체 밝기로 뒤집힌다**(6.5 — colors.ts `strokeFor`). 칩의 선은 전부
   *  이 값 하나다: 차체 테두리 · 볼가드 테두리 · 머리(피벗) 점. 한 칩 안에서 흰 선과 어두운
   *  선이 섞이면 "이 칩의 선 색" 이라는 규칙이 사라지고, 밝은 차체에서 어떤 선이 보이는지가
   *  요소마다 달라진다. */
  stroke: string;
  strokeWidth: number;
  /** 차체 테두리 파선 패턴. `undefined` = 실선. 색을 지워도 남는 **주 채널**이다. */
  strokeDash?: string;
  /** 볼가드 채움. 회색조에서 살아남는 **보조 채널**이다. */
  guardFill: string;
  /** 칩 위에 찍는 글자(등번호 · 골키퍼 'G').
   *  SVG 에는 들어가지 않는다 — 래스터 어댑터가 캔버스에서 그린다(§6.2 [A-9]). */
  label: string;
  /** 글자색. 배경 밝기로 고른다(colors.ts `inkFor` — 팔레트 전체가 ≥4.5:1 이 되는 임계). */
  ink: string;
}

/** 차체 테두리 굵기. ChairChip.tsx 의 본체 `<rect strokeWidth={2.2}>` 과 같은 값이다 —
 *  다르면 내보낸 그림의 칩이 화면과 다른 두께로 보인다. */
export const CHAIR_STROKE_W = 2.2;

/** ChairDef → 팀 표식. `def.color` 개별 지정이 팀 **색**을 덮어쓰는 규칙(§3.5)까지 그대로다.
 *  표식(파선·가드)은 그 덮어쓰기의 영향을 받지 않는다 — 위 `TeamPattern` 주석의 ⚠️ 참고. */
export function teamMarkFor(def: ChairDef, teams: Record<TeamSide, TeamStyle>): TeamMark {
  const team = teams[def.team];
  const fill = def.color ?? (def.isGk ? team.gkColor : team.color);
  const pattern = teamPatternFor(def.team);
  return {
    fill,
    // ⚠️ 6.5 — 여기를 OBJ_STROKE 고정으로 되돌리면 밝은 차체(#e08a12 2.50 · GK어웨이 #22a95b
    // 2.80 · GK홈 #f2c811 1.55)에서 파선 테두리가 3:1 아래로 내려가 **4.6 의 주 채널이
    // 기본 설정에서 사라진다.** 근거·전수 검산은 core/colors.ts 의 strokeFor.
    stroke: strokeFor(fill),
    strokeWidth: CHAIR_STROKE_W,
    strokeDash: pattern.strokeDash,
    guardFill: pattern.guardFill,
    label: def.number,
    ink: inkFor(fill),
  };
}
