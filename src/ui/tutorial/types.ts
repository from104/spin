import type { DictKey } from '../../i18n/ko.ts';

/** 한 단계 — 화면 위 한 요소를 가리키며 설명한다. `target` 은 그 요소의 `data-tut` 속성값
 *  (getBoundingClientRect 로 잰다). 요소가 그 순간 DOM 에 없으면(빈 목록 등) 이 단계는
 *  건너뛴다 — useTutorial 의 계약.
 *  ⚠️ 2026-09-09 보탬: 걸러진 **꼬리** 단계는 앞 단계가 실습형(`advanceOnClick`)이고 그 조작이
 *  실제로 앵커를 그려 냈을 때 되살아난다(화면을 가로지르는 투어 — 팀 투어가 그렇다).
 *  근거와 상한은 `useTutorial.ts` 머리말의 «뒤늦게 오는 단계». */
export interface TutorialStep {
  target: string;
  titleKey: DictKey;
  bodyKey: DictKey;
  /** 실습형 — 구멍 안의 대상을 **실제로 누르면** 그 자체로 다음 단계가 된다
   *  (docs/PLAN-HELP-OVERHAUL.md 결정 11a). [다음] 버튼도 그대로 산다: 손이 닿지 않는
   *  입력(스크린리더·키보드)에는 누를 대상이 없어도 앞으로 갈 길이 있어야 한다.
   *
   *  ⚠️ **되돌릴 수 있는 조작에만 붙인다**(결정 12). 첫 방문자가 안내를 따라 누른 결과로
   *  데이터가 사라지면 안 되므로 삭제·비우기 같은 파괴적 버튼에는 절대 달지 않는다.
   *  값이 `true` 하나뿐인 것도 일부러다 — `false` 를 쓸 수 있게 하면 "실습형이 아니다" 를
   *  두 가지 방식(없음 / false)으로 적게 된다.
   *
   *  ⚠️ **판정은 `closest('[data-tut=…]')` 이라 앵커 안 어디를 눌러도 넘어간다.** 앵커가 버튼
   *  하나가 아니라 묶음(재생 묶음·스텝 틈)에 붙어 있으면 배속 칸이나 여백을 눌러도 "해 봤다"
   *  가 된다. 판정을 요소 하나로 좁히지 않는 이유는 실제 버튼이 아이콘·라벨 같은 자식으로
   *  이뤄져 있어 눌린 것이 그 자식이기 때문이다 — 좁히면 아이콘을 누른 사람이 못 넘어간다.
   *  **실습의 뜻이 정확해야 하는 단계라면 앵커를 그 버튼 자체에 붙인다.** */
  advanceOnClick?: true;
}
