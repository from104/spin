import type { Vec2 } from './units.ts';

export const clamp = (v: number, lo: number, hi: number): number => Math.min(hi, Math.max(lo, v));

/** 벡터 v 의 크기를 m 이하로 자른다 (방향 유지). 크기 0 은 그대로 반환. */
export function clampMag(v: Vec2, m: number): Vec2 {
  const len2 = v.x * v.x + v.y * v.y;
  if (len2 === 0 || len2 <= m * m) return v;
  const scale = m / Math.sqrt(len2);
  return { x: v.x * scale, y: v.y * scale };
}

/** 거리 제곱 (sqrt 회피용, 충돌·근접 판정에 사용). */
export const dist2 = (a: Vec2, b: Vec2): number => {
  const dx = a.x - b.x;
  const dy = a.y - b.y;
  return dx * dx + dy * dy;
};

