/** LUT 를 선형보간한다. t 는 [0,1] 로 클램프. */
function sampleLut(lut: readonly number[], t: number): number {
  if (t <= 0) return 0;
  if (t >= 1) return 1;
  const n = lut.length - 1; // 128
  const x = t * n;
  const i = Math.floor(x);
  const frac = x - i;
  const a = lut[i]!;
  const b = lut[Math.min(i + 1, n)]!;
  return a + (b - a) * frac;
}

export function easeStandard(t: number): number {
  return sampleLut(EASE_STANDARD_LUT, t);
}

/** 가속만 — 연속 구간의 **첫** 스텝이 쓴다(정지에서 출발해 속도를 유지한 채 넘긴다). */
export function easeIn(t: number): number {
  return sampleLut(EASE_ACCEL_LUT, t);
}

/** 감속만 — 연속 구간의 **마지막** 스텝이 쓴다. `easeIn` 의 거울상이다(위 표 주석). */
export function easeOut(t: number): number {
  return 1 - sampleLut(EASE_ACCEL_LUT, 1 - t);
}

/** 등속 — 연속 구간의 **가운데** 스텝이 쓴다. 스텝마다 in-out 을 걸면 키프레임마다 멈칫하므로
 *  구간 안쪽은 가감속을 아예 안 한다(PLAN-STEP-LINK 결정 3). */
export function easeLinear(t: number): number {
  return t <= 0 ? 0 : t >= 1 ? 1 : t;
}
