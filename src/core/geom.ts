/** LUT 를 선형보간한다. t 는 [0,1] 로 클램프. */
export function easeStandard(t: number): number {
  if (t <= 0) return 0;
  if (t >= 1) return 1;
  const n = EASE_STANDARD_LUT.length - 1; // 128
  const x = t * n;
  const i = Math.floor(x);
  const frac = x - i;
  const a = EASE_STANDARD_LUT[i]!;
  const b = EASE_STANDARD_LUT[Math.min(i + 1, n)]!;
  return a + (b - a) * frac;
}
