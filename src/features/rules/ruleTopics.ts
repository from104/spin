// 🪦 `contested`(경합: 누구 터치아웃?) 주제 폐기 — 2026-08-31, PLAN-RULES-9CARDS.md §3.2.
// 독립 주제로 세운 근거는 "동시 접촉 판정이 눈에 띄는 조항이고 `contested-touch` 장면의 집이
// 필요하다"였는데, 같은 판정문이 정본에서 Law 15(킥인) 안에 있다(RULES-FIPFA-2025.md L260).
// 즉 "독립 주제"는 정본 구조에 없던 앱의 창작이었고, 산문 2문장 + 장면 1개로 카드 홈에서
// 다른 카드와 같은 크기를 차지하고 있었다. 판정 문장과 `contested-touch` 장면은 카드 5
// (`restarts`)의 마지막 두 블록으로 함께 옮겼다(고아 장면 0 유지). 첫 문장 "마지막으로 건드린
// 팀의 상대에게 킥인"은 처음엔 "표가 이미 말한다"는 이유로 뺐는데, 이는 사실이 아니었다 —
// `restartTable.ts` 의 킥인 열은 `when: '터치라인 아웃'` 까지만 말하고 누가 얻는지는 어느 셀에도
// 없다. 2026-08-31 적대 검수가 잡아, 이 문장을 카드 5 블록 5(`동시에 건드렸으면 누구 것?`)
// 산문 맨 앞에 되살렸다(정본 L258). 같은 사실은 `ruleScenes.ts` 의 `inout`·`kick-in` 장면 스텝
// 노트와 `ruleContent.ts` 제15조 요약에도 남아 있다.
// 딥링크 `/rules/contested` 는 `routes.ts` 의 단방향 흡수 분기가 `restarts` 로 받는다.

export type RuleBlock =
  | { kind: 'prose'; heading?: string; body: readonly string[] }
  | { kind: 'figure'; figureId: RuleFigureId }
  | { kind: 'scene'; sceneId: RuleSceneId }
  /**
   * 장면 자리만 잡아 두는 블록 — 화면에는 **아무것도 뜨지 않는다**(`renderBlock` 이 null 반환).
   * "준비 중"·"coming soon" 류 자리표시자를 배송하지 않는 것이 요점이다: 반쯤 완성된 장면이
   * 안 뜨는 것 = 아예 안 뜨는 것. `note` 는 화면 문구가 아니라 **장면을 만들 다음 사람에게
   * 남기는 메모**이고, 어느 산문 뒤에 꽂히는지가 주석이 아니라 `blocks` 배열의 인덱스로
   * 기록된다. 시연 장면은 기현님이 드릴 편집기로 직접 만든다(2026-08-23 결정).
   *
   * 필드 이름이 `heading?`·`body` 였던 것을 2026-08-31 에 `note` 하나로 줄였다: 다른 블록에서
   * `heading`·`body` 는 **화면에 뜨는 문구**를 뜻하는데 여기서는 둘 다 버려진다. 이름이 거짓말을
   * 하면 다음 사람이 `heading` 을 채워 놓고 왜 안 뜨는지 찾게 된다.
   */
  | { kind: 'scene-slot'; note: readonly string[] }
  /** 재개 7종 비교표 — 데이터는 `restartTable.ts` 단일 출처, 주제당 최대 1개. */
  | { kind: 'restart-table' }
  /** 경고 7종·퇴장 8종 — 데이터는 이 파일의 `MISCONDUCT_CARDS`, 주제당 최대 1개. */
  | { kind: 'card-list' }
  /** 부록: 18개조 압축표 — 데이터는 `ruleContentFor(locale)`, 주제당 최대 1개. */
  | { kind: 'law-index' };

export interface RuleTopic {
  key: RuleTopicKey;
  title: string;
  tagline: string;
  blocks: readonly RuleBlock[];
  /**
   * 이 카드에 걸리는 튜토리얼 앵커(`data-tut`). 카드 홈의 튜토리얼 3단계 중 2·3단계가 특정
   * 카드를 가리키는데, 어느 카드인지는 **화면 순서가 아니라 여기**에서 정한다
   * (PLAN-RULES-9CARDS.md §8-7).
   *
   * 2026-08-31 이전에는 `RulesHome` 이 "첫 카드 = `rules-card`" 라는 위치 삼항으로 걸었고,
   * 9카드 개편으로 첫 카드가 `basics` → `intro` 로 바뀌면서 튜토리얼이 실제로 어긋났다:
   * 2단계 본문(`tutorial.rules.step2.body`)은 "카드마다 담긴 도해·장면 개수가 배지로 보입니다"
   * 라고 배지를 설명하는데 `intro` 는 prose 와 scene-slot 뿐이라 `topicMeta()` 가 빈 배열을
   * 낸다 — 배지가 하나도 없는 카드를 가리키며 배지를 설명했다. 이 앵커를 지키는 테스트가
   * 하나도 없어서 CI 는 조용했다.
   */
  tutorialAnchor?: 'rules-card' | 'rules-appendix';
}

