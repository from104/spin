// 이동 앵커가 **무엇을 감싸고 무엇을 옮기는가**. 순수 함수 하나(§6.10d, 2026-09-13).
//
// 왜 따로 두나: 이 명단이 두 곳에서 쓰인다 — 앵커가 뜰 상자를 재는 곳(EditorStage)과, 앵커를
// 눌렀을 때 실제로 미는 곳(useEditorPointer). 두 곳이 각자 명단을 만들면 언젠가 갈라지고,
// 갈라지는 순간 **앵커가 감싼 것과 옮겨지는 것이 달라진다** — 화면이 거짓말하는 부류의 사고다.
import { isId } from '../../core/ids.ts';

/**
 * 지금 선택에서 앵커가 다룰 id 들. 앵커를 띄우지 않을 자리에서는 **빈 배열**이다.
 *
 * 규칙 둘:
 * ① 잠긴 것·무시된 것은 뺀다 — 눌러도 안 움직이는 것을 감싼 앵커는 고장 난 버튼이다.
 * ② 거르고 **하나만 남았다면** 그것이 도형(`sh`)이나 메모(`nt`)일 때만 낸다.
 *
 * ②의 허용 목록은 기현님 지시 둘이 함께 정한다 — 2026-09-13 *"도형, 메모, 다중 선택에서…"* 와
 * 2026-09-14 *"선, 자유선에도 적용"*. 휠체어·공·콘 하나가 빠지는 이유는
 * 크기가 아니라 **회로**다: 그 셋은 몸통을 잡으면 물리 드래그(견인·회전·충돌·리시)가 열리는데,
 * 앵커는 모델을 직접 미는 길이라 같은 손짓이 다른 이동이 된다. 겹쳐서 못 집는 문제도 그 셋에는
 * 거의 없다 — 몸통이 넓고, 가리면 표시순서로 꺼낸다.
 *
 * ⚠️ 2026-09-14 — 위 문단의 *"화살표·획이 하나일 때도 빠진다: 그쪽은 몸통 어디를 잡아도 끌리고,
 * 이미 제 손잡이가 있다"* 는 기현님 지시로 **뒤집혔다**(*"일단 선, 자유선에도 적용하고"*).
 * 근거는 지우지 않는다 — 틀린 말이 아니었고, 다만 전제가 좁았다: «몸통 어디를 잡아도 끌린다» 는
 * 그 선이 **맨 위에 있을 때만** 참이다. 가는 선은 겹치면 도형·메모보다 오히려 집기 어렵고,
 * 제 손잡이는 끝점·굽힘점을 **바꾸는** 것이라 통째로 옮기는 손잡이가 아니다.
 * 휠체어·공·콘은 그대로 빠진다(위 ②의 근거는 아직 살아 있다).
 */
export function moveAnchorIds(
  selection: ReadonlySet<string>,
  locked?: ReadonlySet<string>,
  ignored?: ReadonlySet<string>,
): string[] {
  const ids = Array.from(selection).filter((id) => !locked?.has(id) && !ignored?.has(id));
  if (ids.length === 0) return [];
  if (ids.length === 1) {
    const only = ids[0]!;
    if (!isId(only, 'sh') && !isId(only, 'nt') && !isId(only, 'ar') && !isId(only, 'fh')) return [];
  }
  return ids;
}

/**
 * 이 선택에 **가이드 사각형**을 그리는가(§6.10e, 2026-09-14 기현님 지시).
 *
 * 기준 하나: **감싼 상자가 개체의 몸통과 다를 때만** 그린다.
 * - 여럿 → 그린다. 상자가 어느 개체와도 안 맞아 앵커가 허공에 뜬 것처럼 보인다(지적의 원문).
 * - 선·자유선 하나 → 그린다. 가늘고 비스듬한 선의 AABB 는 선 자체와 전혀 달라 같은 일이 난다.
 * - 도형 하나 → 안 그린다. 손잡이 셋이 이미 상자를 말한다.
 * - 메모 하나 → 안 그린다. 선택 링이 이미 칩을 감싸고 있다.
 *
 * 안 그리는 둘에 굳이 그리면 판 위에 사각형이 하나 더 늘 뿐이다 — 규칙 존·러버밴드·도형과
 * 겹쳐 읽히는 위험만 커진다.
 */
export function moveAnchorGuide(ids: readonly string[]): boolean {
  if (ids.length === 0) return false;
  if (ids.length > 1) return true;
  const only = ids[0]!;
  return isId(only, 'ar') || isId(only, 'fh');
}
