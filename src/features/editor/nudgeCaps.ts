// 「이 개체를 키보드·패드로 **옮길 수 있는가·돌릴 수 있는가**」의 유일한 출처.
//
// ⚠️ 2026-09-14 — 이 두 함수는 `NudgePad.tsx` 안에 살았다. 화면 부품 안에 판정이 있으면 그것을
// 읽지 않는 길이 생기고, 실제로 생겼다: 터치 패드는 획(`fh`)을 **돌릴 수 있었는데** 키보드 Q·E 는
// `if (!isId(id, 'ch')) return;` 으로 휠체어만 돌렸다. 같은 앱에서 손가락으로 되는 일이 키보드로
// 안 되는 자리다(§7.5 가 금지하는 바로 그 비대칭). 판정을 부품 밖으로 꺼내 **세 문**(키보드·
// [미세 조정] 패드·개체 메뉴)이 한 답을 쓰게 한다.
import { isId } from '../../core/ids.ts';

/** 미세 조정이 **먹는** 개체인가.
 *
 *  ⚠️ 2026-09-14 — 옛 주석은 *"도형(`sh`)은 `EditorStage.nudge` 에서도 빠져 있어 여기서도
 *  뺀다(있는데 안 먹는 칸을 내지 않는다)"* 였다. 근거는 옳았고 **전제가 고쳐졌다**: 이제 도형도
 *  키보드로 움직인다(기현님 지시 *"모든 객체가 wasd,qe 키에 의해 위치 및 회전이 되어야한다"*).
 *  그러니 여기서도 낸다 — 두 곳이 갈라지지 않게 하는 것이 이 파일의 존재 이유다. */
export const canNudge = (ids: readonly string[]): boolean =>
  ids.length > 0 &&
  ids.every(
    (id) =>
      isId(id, 'ch') ||
      isId(id, 'bl') ||
      isId(id, 'cn') ||
      isId(id, 'nt') ||
      isId(id, 'ar') ||
      isId(id, 'fh') ||
      isId(id, 'sh'),
  );

/** 회전이 **뜻을 갖는** 종류인가 — 축이 값 하나로 정해지는 넷.
 *
 *  · 휠체어(`ch`) — 방향을 가진 유일한 캐스트. 축은 피벗.
 *  · 도형(`sh`) — `rot`(도, 시계방향). 축은 `x,y`(삼각형은 무게중심).
 *  · 화살표(`ar`) — 축은 `arrowMid`(곡선의 t=0.5 점). 포인터의 회전 앵커와 같은 축이다.
 *  · 획(`fh`) — 축은 경계상자 중심(`strokeCenter`). 역시 포인터와 같은 축.
 *
 *  빠지는 셋에는 **돌릴 것이 없다**: 공은 원이라 돌아도 같은 그림이고, 콘·메모는 모델에 각도
 *  필드 자체가 없다. 메모는 기현님이 명시적으로 예외로 지정하기도 했다(*"단 메모와 다중
 *  선택에서 회전은 예외"*) — 없는 것을 굳이 만들지 않는다는 뜻이라 코드와 지시가 같다.
 *
 *  ⚠️ 2026-09-14 — 옛 주석의 *"화살표가 빠지는 것은 원리가 아니라 아직 안 이은 배선이다 …
 *  뒤집을 때 이 문장이 근거가 되라고 적어 둔다"* 는 그 약속대로 지금 뒤집혔다. */
export const canRotateKind = (id: string): boolean =>
  isId(id, 'ch') || isId(id, 'sh') || isId(id, 'ar') || isId(id, 'fh');

/** 회전은 **하나일 때만**이다.
 *
 *  무리의 회전축은 답이 하나로 안 나온다(`applyGroupNudge` 주석) — 무게중심인지, 감싼 상자의
 *  중심인지, 포커스가 앉은 개체인지. 기현님도 같은 자리를 예외로 지정했다: *"다중 선택에서
 *  회전은 예외"*. 그래서 이 함수는 개수부터 본다. */
export const canRotate = (ids: readonly string[]): boolean => ids.length === 1 && canRotateKind(ids[0]!);
